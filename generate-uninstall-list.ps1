# Writes uninstall-files.nsh for installer.nsi: one Delete line per file in the
# publish folder and one RMDir line per sub-folder (deepest first), so the
# uninstaller removes exactly what was installed. Run automatically by makensis.
param(
    [string]$PublishDir = "publish",
    [string]$OutFile = "uninstall-files.nsh"
)

$ErrorActionPreference = "Stop"
$root = (Resolve-Path -LiteralPath $PublishDir).Path.TrimEnd('\', '/')

function To-NsisPath([string]$fullName) {
    # Relative path under $INSTDIR; '$' must be doubled in NSIS strings
    $rel = $fullName.Substring($root.Length + 1).Replace('/', '\').Replace('$', '$$')
    return '$INSTDIR\' + $rel
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("; Generated by generate-uninstall-list.ps1 from $PublishDir - do not edit")

Get-ChildItem -LiteralPath $root -Recurse -File | Sort-Object FullName | ForEach-Object {
    $lines.Add('  Delete "' + (To-NsisPath $_.FullName) + '"')
}

Get-ChildItem -LiteralPath $root -Recurse -Directory |
    Sort-Object { $_.FullName.Length } -Descending | ForEach-Object {
        $lines.Add('  RMDir "' + (To-NsisPath $_.FullName) + '"')
    }

if ([System.IO.Path]::IsPathRooted($OutFile)) { $outPath = $OutFile }
else { $outPath = Join-Path (Get-Location) $OutFile }
[System.IO.File]::WriteAllLines($outPath, $lines, (New-Object System.Text.UTF8Encoding $true))
Write-Host "Wrote $($lines.Count - 1) uninstall entries to $outPath"
